-- Reviews: anyone can read
CREATE POLICY "Reviews are viewable by everyone"
  ON public.product_reviews FOR SELECT USING (true);

-- Reviews: customer can insert only for a product they purchased, and only once
-- (the UNIQUE constraint enforces one-per-customer-per-product)
CREATE POLICY "Customers can insert reviews for purchased products"
  ON public.product_reviews FOR INSERT
  WITH CHECK (
    auth.uid() = customer_id
    AND EXISTS (
      SELECT 1 FROM public.order_items oi
      JOIN public.orders o ON o.id = oi.order_id
      WHERE o.customer_id = auth.uid()
      AND oi.product_id = product_reviews.product_id
    )
  );

-- Reviews: customer can update/delete only their own
CREATE POLICY "Customers can update own reviews"
  ON public.product_reviews FOR UPDATE USING (auth.uid() = customer_id);

CREATE POLICY "Customers can delete own reviews"
  ON public.product_reviews FOR DELETE USING (auth.uid() = customer_id);

-- Review images: anyone can read
CREATE POLICY "Review images are viewable by everyone"
  ON public.product_review_images FOR SELECT USING (true);

-- Review images: owner of the parent review can manage
CREATE POLICY "Customers can manage own review images"
  ON public.product_review_images FOR ALL USING (
    EXISTS (
      SELECT 1 FROM public.product_reviews pr
      WHERE pr.id = product_review_images.review_id
      AND pr.customer_id = auth.uid()
    )
  );
