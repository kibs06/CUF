-- Virtual fitting AR effects: uploaded `.deepar` Studio files, one live row per
-- product, served to the app + customer portal instead of files bundled in a
-- release. An admin uploads from the 3D-products shelf; until then the bundled
-- Luna/Luxe effects in the clients remain the fallback.
-- ══════════════════════════════════════════════════════════════════════════

-- ──────────────────────────────────────────────────────────────────
-- 1. product_ar_effects
-- ──────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.product_ar_effects (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- products.id is UUID. Same correction as product_models: a TEXT FK would
    -- fail on the first insert.
    product_id        UUID NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    storage_path      TEXT NOT NULL,            -- shoe-ar-effects/<product_id>/<sha>.deepar
    sha256            TEXT NOT NULL,            -- cache key + integrity check (lowercase hex)
    version           INT NOT NULL DEFAULT 1 CHECK (version >= 1),
    file_size_bytes   INT CHECK (file_size_bytes IS NULL OR file_size_bytes > 0),
    status            TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('draft', 'active', 'rejected')),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT product_ar_effects_sha256_shape_check
      CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT product_ar_effects_storage_path_not_blank_check
      CHECK (btrim(storage_path) <> '')
);

-- One product has at most one row per version. Duplicates would make the
-- resolver non-deterministic — the same trap product_models avoids.
CREATE UNIQUE INDEX IF NOT EXISTS uq_product_ar_effects_version
  ON public.product_ar_effects (product_id, version);

-- The read path is always "active effect of this product".
CREATE INDEX IF NOT EXISTS idx_product_ar_effects_product_active
  ON public.product_ar_effects (product_id);

DROP TRIGGER IF EXISTS trg_product_ar_effects_updated_at ON public.product_ar_effects;
CREATE TRIGGER trg_product_ar_effects_updated_at
  BEFORE UPDATE ON public.product_ar_effects
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

COMMENT ON TABLE public.product_ar_effects IS
  'Virtual fitting AR: one row per uploaded .deepar Studio effect. active rows are served to customers; draft/rejected are work items.';
COMMENT ON COLUMN public.product_ar_effects.product_id IS
  'products.id (UUID). An effect belongs to exactly one product.';
COMMENT ON COLUMN public.product_ar_effects.storage_path IS
  'Object path inside the public `shoe-ar-effects` bucket: <product_id>/<sha256>.deepar.';
COMMENT ON COLUMN public.product_ar_effects.sha256 IS
  'Lowercase SHA-256 of the uploaded .deepar. Device cache key + integrity check.';

-- ──────────────────────────────────────────────────────────────────
-- 2. RLS — active rows are catalog content (same shape as product_models)
-- ──────────────────────────────────────────────────────────────────
ALTER TABLE public.product_ar_effects ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Active AR effects are viewable by everyone"
  ON public.product_ar_effects;
CREATE POLICY "Active AR effects are viewable by everyone"
  ON public.product_ar_effects FOR SELECT
  USING (
    status = 'active'
    OR public.is_admin()
    OR EXISTS (
      SELECT 1 FROM public.products p
      JOIN public.stores s ON s.id = p.store_id
      WHERE p.id = product_ar_effects.product_id AND s.owner_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Sellers can insert AR effects for their products"
  ON public.product_ar_effects;
CREATE POLICY "Sellers can insert AR effects for their products"
  ON public.product_ar_effects FOR INSERT
  WITH CHECK (
    public.is_admin()
    OR EXISTS (
      SELECT 1 FROM public.products p
      JOIN public.stores s ON s.id = p.store_id
      WHERE p.id = product_ar_effects.product_id AND s.owner_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Sellers can update AR effects for their products"
  ON public.product_ar_effects;
CREATE POLICY "Sellers can update AR effects for their products"
