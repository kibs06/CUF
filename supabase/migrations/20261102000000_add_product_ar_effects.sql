-- ──────────────────────────────────────────────────────────────────
-- 3. The shoe-ar-effects bucket
-- ──────────────────────────────────────────────────────────────────
-- Public read: an effect is catalog content and the portal loads it by its
-- public URL. 32 MB cap — Studio exports run ~16 MB, so 8 MB would refuse
-- real files. MIME is octet-stream: a .deepar is an opaque Studio binary and
-- must not be refused for not being a web type.
--
-- NOTE: buckets created here with INSERT ... ON CONFLICT, the same route
-- `shoe-models` took — if a future storage API rejects the insert, the
-- Dashboard fallback is Storage → New bucket.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'shoe-ar-effects',
  'shoe-ar-effects',
  true,
  33554432, -- 32 MB
  ARRAY['application/octet-stream']
)
ON CONFLICT (id) DO UPDATE
  SET public = EXCLUDED.public,
      file_size_limit = EXCLUDED.file_size_limit,
      allowed_mime_types = EXCLUDED.allowed_mime_types;

-- Public read of effect objects.
DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE policyname = 'Public can view shoe AR effects' AND tablename = 'objects'
    ) THEN
        CREATE POLICY "Public can view shoe AR effects"
            ON storage.objects FOR SELECT
            USING (bucket_id = 'shoe-ar-effects');
    END IF;
END $$;

-- Seller upload: the first path segment is the product id, and the product's
-- store must be one they own — so a seller cannot overwrite another seller's
-- effect even with a known path. Compared as text so a malformed path can
-- never raise a cast error inside a policy.
DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE policyname = 'Sellers can upload shoe AR effects' AND tablename = 'objects'
    ) THEN
        CREATE POLICY "Sellers can upload shoe AR effects"
            ON storage.objects FOR INSERT
            WITH CHECK (
                bucket_id = 'shoe-ar-effects'
                AND (
                    public.is_admin()
                    OR EXISTS (
                        SELECT 1 FROM public.products p
                        JOIN public.stores s ON s.id = p.store_id
                        WHERE p.id::text = (storage.foldername(name))[1]
                          AND s.owner_id = auth.uid()
                    )
                )
            );
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE policyname = 'Sellers can update shoe AR effects' AND tablename = 'objects'
    ) THEN
        CREATE POLICY "Sellers can update shoe AR effects"
            ON storage.objects FOR UPDATE
            USING (
                bucket_id = 'shoe-ar-effects'
                AND (
                    public.is_admin()
                    OR EXISTS (
                        SELECT 1 FROM public.products p
                        JOIN public.stores s ON s.id = p.store_id
                        WHERE p.id::text = (storage.foldername(name))[1]
                          AND s.owner_id = auth.uid()
                    )
                )
            );
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE policyname = 'Sellers can delete shoe AR effects' AND tablename = 'objects'
    ) THEN
        CREATE POLICY "Sellers can delete shoe AR effects"
            ON storage.objects FOR DELETE
            USING (
                bucket_id = 'shoe-ar-effects'
                AND (
                    public.is_admin()
                    OR EXISTS (
                        SELECT 1 FROM public.products p
                        JOIN public.stores s ON s.id = p.store_id
                        WHERE p.id::text = (storage.foldername(name))[1]
                          AND s.owner_id = auth.uid()
                    )
                )
            );
    END IF;
END $$;

